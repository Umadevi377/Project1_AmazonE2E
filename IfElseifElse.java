package module1.basic;

public class IfElseifElse
{
	public static void main(String[] args)
	
	{
		int a = 100;
		int b = 20;
		if(a >= b) //if condition is true:    " first condition only execute
			
		{
			System.out.println("If block will print:First condition  ");
			
		}
		
		else if(a>b)//can be true  
		{
			System.out.println("Second condtion ");
			
		}
				
		else
		{
			System.out.println("else block execute");
		}
		
	}

}
